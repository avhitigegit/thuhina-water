-- M15 Expenses (design 4.3 "Expenses", FR-62, FR-63, BR-19)
-- Running expenses kept month by month. Each expense counts in the month it is FOR (for_month, first day of the month),
-- not the month it was paid: September electricity paid on 02/10 counts for September. Numbers EX-0001 come from the
-- EXPENSE sequence created in V001. Deleting needs a reason and is a soft delete, so the audit trail stays complete.

-- ---------------------------------------------------------------- expense types (FR-63)
CREATE TABLE expense_type (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(200),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  VARCHAR(50)  NOT NULL DEFAULT 'system',
    updated_at  TIMESTAMPTZ,
    updated_by  VARCHAR(50),
    version     BIGINT       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_expense_type_name ON expense_type (lower(name));

