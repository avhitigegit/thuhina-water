-- ---------------------------------------------------------------- expenses (FR-62)
CREATE TABLE expense (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_no      VARCHAR(20)   NOT NULL,
    paid_date       DATE          NOT NULL,
    for_month       DATE          NOT NULL,
    expense_type_id BIGINT        NOT NULL REFERENCES expense_type (id),
    description     VARCHAR(200),
    paid_to         VARCHAR(100),
    bill_no         VARCHAR(50),
    amount          NUMERIC(14,2) NOT NULL,
    method          VARCHAR(20)   NOT NULL,
    reference       VARCHAR(100),
    deleted         BOOLEAN       NOT NULL DEFAULT FALSE,
    delete_reason   VARCHAR(200),
    deleted_at      TIMESTAMPTZ,
    deleted_by      VARCHAR(50),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by      VARCHAR(50)   NOT NULL DEFAULT 'system',
    updated_at      TIMESTAMPTZ,
    updated_by      VARCHAR(50),
    version         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ux_expense_no UNIQUE (expense_no),
    CONSTRAINT ck_expense_month CHECK (for_month = date_trunc('month', for_month)::date),
    CONSTRAINT ck_expense_amount CHECK (amount > 0),
    CONSTRAINT ck_expense_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_expense_reference CHECK (method = 'CASH' OR reference IS NOT NULL),
    CONSTRAINT ck_expense_deleted CHECK (NOT deleted OR (delete_reason IS NOT NULL AND deleted_at IS NOT NULL AND deleted_by IS NOT NULL))
);
CREATE INDEX ix_expense_month ON expense (for_month) WHERE NOT deleted;
CREATE INDEX ix_expense_type ON expense (expense_type_id);

-- ---------------------------------------------------------------- audit: deleting an expense is logged as DELETE
ALTER TABLE audit_log DROP CONSTRAINT ck_audit_log_action;
ALTER TABLE audit_log ADD CONSTRAINT ck_audit_log_action
    CHECK (action IN ('CREATE', 'UPDATE', 'DELETE', 'APPROVE', 'REVERSE', 'IMPORT', 'LOGIN', 'LOGOUT'));
