-- M16 Customer quotations (design 4.3 "Customer quotations", FR-64 – FR-66, BR-20)
-- Price quotations to an existing customer or to a new organisation. Steps: DRAFT → SENT → ACCEPTED / REJECTED (shown as
-- "Not accepted"); "Expired" is not stored – it is a SENT quotation past its valid-until date. Only a draft can be changed.
-- Numbers QT-2026-001 come from the CUSTOMER_QUOTATION sequence created in V001 (yearly).
-- An accepted quotation sets agreed prices (customer_price.customer_quotation_id) at registration or with "Apply prices".

CREATE TABLE customer_quotation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cq_no             VARCHAR(20)  NOT NULL,
    customer_id       BIGINT       REFERENCES customer (id),
    org_name          VARCHAR(150) NOT NULL,
    contact           VARCHAR(100),
    designation       VARCHAR(100),
    address           VARCHAR(250),
    area_id           BIGINT       REFERENCES area (id),
    phone             VARCHAR(20),
    email             VARCHAR(100),
    customer_type_id  BIGINT       NOT NULL REFERENCES customer_type (id),
    quote_date        DATE         NOT NULL,
    valid_until       DATE         NOT NULL,
    subject           VARCHAR(200),
    delivery_text     VARCHAR(200),
    terms_days        INTEGER      NOT NULL,
    conditions        TEXT,
    status            VARCHAR(10)  NOT NULL DEFAULT 'DRAFT',
    sent_via          VARCHAR(10),
    sent_on           DATE,
    accepted_on       DATE,
    reject_reason     VARCHAR(250),
    prices_applied_on DATE,
    copy_of_id        BIGINT       REFERENCES customer_quotation (id),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by        VARCHAR(50)  NOT NULL DEFAULT 'system',
    updated_at        TIMESTAMPTZ,
    updated_by        VARCHAR(50),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ux_customer_quotation_no UNIQUE (cq_no),
    CONSTRAINT ck_customer_quotation_status CHECK (status IN ('DRAFT', 'SENT', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_customer_quotation_valid CHECK (valid_until >= quote_date),
    CONSTRAINT ck_customer_quotation_terms CHECK (terms_days IN (0, 7, 14, 30, 45, 60)),
    CONSTRAINT ck_customer_quotation_via CHECK (sent_via IS NULL OR sent_via IN ('EMAIL', 'BY_HAND', 'POST', 'WHATSAPP')),
    CONSTRAINT ck_customer_quotation_sent CHECK (status = 'DRAFT' OR (sent_via IS NOT NULL AND sent_on IS NOT NULL)),
    CONSTRAINT ck_customer_quotation_accepted CHECK (status <> 'ACCEPTED' OR accepted_on IS NOT NULL),
    CONSTRAINT ck_customer_quotation_rejected CHECK (status <> 'REJECTED' OR reject_reason IS NOT NULL),
    CONSTRAINT ck_customer_quotation_applied CHECK (prices_applied_on IS NULL OR (status = 'ACCEPTED' AND customer_id IS NOT NULL))
);
CREATE INDEX ix_customer_quotation_customer ON customer_quotation (customer_id);
CREATE INDEX ix_customer_quotation_status ON customer_quotation (status, valid_until);

-- Lines: water or deposit per bottle type, a product, or free text. current_price = what the customer would pay when quoted
-- (their agreed or standard water price, the deposit, the product's selling price) – shown beside a changed price.
CREATE TABLE cq_line (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id     BIGINT        NOT NULL REFERENCES customer_quotation (id) ON DELETE CASCADE,
    line_no          INTEGER       NOT NULL,
    item_kind        VARCHAR(10)   NOT NULL,
    bottle_type_code VARCHAR(10)   REFERENCES bottle_type (code),
    product_code     VARCHAR(10),
    description      VARCHAR(200)  NOT NULL,
    qty              INTEGER       NOT NULL,
    unit             VARCHAR(30),
    unit_price       NUMERIC(12,2) NOT NULL,
    current_price    NUMERIC(12,2),
    current_agreed   BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT ux_cq_line UNIQUE (quotation_id, line_no),
    CONSTRAINT ck_cq_line_kind CHECK (item_kind IN ('WATER', 'DEPOSIT', 'PRODUCT', 'OTHER')),
    CONSTRAINT ck_cq_line_item CHECK (
        (item_kind IN ('WATER', 'DEPOSIT') AND bottle_type_code IS NOT NULL AND product_code IS NULL)
        OR (item_kind = 'PRODUCT' AND product_code IS NOT NULL AND bottle_type_code IS NULL)
        OR (item_kind = 'OTHER' AND bottle_type_code IS NULL AND product_code IS NULL)),
    CONSTRAINT ck_cq_line_qty CHECK (qty >= 1),
    CONSTRAINT ck_cq_line_price CHECK (unit_price >= 0)
);

-- Every step, edit, copy, registration and price application, with who and when (the quotation's history).
CREATE TABLE cq_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT       NOT NULL REFERENCES customer_quotation (id),
    event        VARCHAR(20)  NOT NULL,
    note         VARCHAR(250),
    ts           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    username     VARCHAR(50)  NOT NULL,
    CONSTRAINT ck_cq_history_event CHECK (event IN ('CREATED', 'EDITED', 'SENT', 'ACCEPTED', 'REJECTED', 'CUSTOMER_LINKED', 'PRICES_APPLIED'))
);
CREATE INDEX ix_cq_history_quotation ON cq_history (quotation_id, ts);
CREATE TRIGGER tr_cq_history_insert_only BEFORE UPDATE OR DELETE ON cq_history
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();

-- Agreed prices set from a quotation keep the link (the column exists since V006).
ALTER TABLE customer_price ADD CONSTRAINT fk_customer_price_quotation
    FOREIGN KEY (customer_quotation_id) REFERENCES customer_quotation (id);
