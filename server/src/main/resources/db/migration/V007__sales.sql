-- M06 Sales core (design 4.3 "Sales", 5.1, 5.2, 5.6)
-- Every sale is a sales transaction (bill) with lines; stock and customer bottles change through the Ledger Engine,
-- the account balance through customer_account. Bill numbers come from the BILL sequence (B000001) created in V001.

CREATE TABLE sales_txn (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_no            VARCHAR(20)   NOT NULL,
    paper_bill_no      VARCHAR(30),
    kind               VARCHAR(20)   NOT NULL,
    txn_date           DATE          NOT NULL,
    customer_id        BIGINT        REFERENCES customer (id),
    walk_in_name       VARCHAR(120),
    amount             NUMERIC(12,2) NOT NULL,
    paid_on_bill       NUMERIC(12,2) NOT NULL DEFAULT 0,
    pay_method         VARCHAR(15),
    water_amount       NUMERIC(12,2) NOT NULL DEFAULT 0,
    deposit_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    product_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    product_cost       NUMERIC(12,2) NOT NULL DEFAULT 0,
    note               VARCHAR(500),
    phone_confirmed    BOOLEAN       NOT NULL DEFAULT FALSE,
    damage_mode        VARCHAR(10),
    settle_method      VARCHAR(10),
    credit_override_by VARCHAR(50),
    reversal_of_id     BIGINT        REFERENCES sales_txn (id),
    reversed_by_id     BIGINT        REFERENCES sales_txn (id),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by         VARCHAR(50)   NOT NULL DEFAULT 'system',
    updated_at         TIMESTAMPTZ,
    updated_by         VARCHAR(50),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ux_sales_txn_bill_no UNIQUE (bill_no),
    CONSTRAINT ck_sales_txn_kind CHECK (kind IN ('FIRST_PURCHASE', 'EXCHANGE', 'LEFT_AT_DOOR', 'COLLECT_EMPTIES', 'EXTRA_ORDER',
        'PRODUCT_SALE', 'CUSTOMER_DAMAGE', 'OWED_SETTLEMENT', 'OPENING_BALANCE', 'REVERSAL')),
    CONSTRAINT ck_sales_txn_party CHECK (customer_id IS NOT NULL OR (kind IN ('PRODUCT_SALE', 'REVERSAL') AND walk_in_name IS NOT NULL)),
    CONSTRAINT ck_sales_txn_paid CHECK (kind = 'REVERSAL' OR paid_on_bill >= 0),
    CONSTRAINT ck_sales_txn_pay_method CHECK (pay_method IS NULL OR pay_method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_sales_txn_damage_mode CHECK (damage_mode IS NULL OR damage_mode IN ('REPLACE', 'REDUCE')),
    CONSTRAINT ck_sales_txn_settle CHECK (settle_method IS NULL OR settle_method IN ('RETURN', 'DEPOSIT'))
);
CREATE INDEX ix_sales_txn_customer_date ON sales_txn (customer_id, txn_date);
CREATE INDEX ix_sales_txn_date ON sales_txn (txn_date);
CREATE INDEX ix_sales_txn_kind_date ON sales_txn (kind, txn_date);

-- BR-13: a paper bill number can be entered only once – among bills that are not reversed and are not reversals,
-- so a reversed bill's number can be entered again.
CREATE UNIQUE INDEX ux_paper_bill ON sales_txn (upper(paper_bill_no))
    WHERE paper_bill_no IS NOT NULL AND kind <> 'REVERSAL' AND reversed_by_id IS NULL;

CREATE TABLE sales_txn_line (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id             BIGINT        NOT NULL REFERENCES sales_txn (id),
    line_no            INTEGER       NOT NULL,
    bottle_type_code   VARCHAR(10)   REFERENCES bottle_type (code),
    product_code       VARCHAR(10),
    filled             INTEGER       NOT NULL DEFAULT 0,
    empties            INTEGER       NOT NULL DEFAULT 0,
    unit_price         NUMERIC(12,2),
    agreed_price       BOOLEAN       NOT NULL DEFAULT FALSE,
    deposit_unit       NUMERIC(12,2),
    deposit_count      INTEGER       NOT NULL DEFAULT 0,
    old_bottles        INTEGER       NOT NULL DEFAULT 0,
    old_brand_id       BIGINT        REFERENCES old_bottle_brand (id),
    new_bottles        INTEGER       NOT NULL DEFAULT 0,
    owed_added         INTEGER       NOT NULL DEFAULT 0,
    owed_cleared       INTEGER       NOT NULL DEFAULT 0,
    to_collect_added   INTEGER       NOT NULL DEFAULT 0,
    to_collect_cleared INTEGER       NOT NULL DEFAULT 0,
    damaged            INTEGER       NOT NULL DEFAULT 0,
    qty                INTEGER       NOT NULL DEFAULT 0,
    unit_cost          NUMERIC(12,2),
    line_amount        NUMERIC(12,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_sales_line_item CHECK ((bottle_type_code IS NULL) <> (product_code IS NULL))
);
CREATE INDEX ix_sales_txn_line_txn ON sales_txn_line (txn_id);
CREATE INDEX ix_sales_txn_line_brand ON sales_txn_line (old_brand_id) WHERE old_brand_id IS NOT NULL;

-- Bills, lines and amounts never change after saving; only the reversal link (reversed_by_id) is set later.
CREATE FUNCTION sales_txn_guard() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'sales_txn is insert-only – reverse the bill instead';
    END IF;
    IF NEW.bill_no IS DISTINCT FROM OLD.bill_no OR NEW.kind IS DISTINCT FROM OLD.kind OR NEW.txn_date IS DISTINCT FROM OLD.txn_date
        OR NEW.customer_id IS DISTINCT FROM OLD.customer_id OR NEW.amount IS DISTINCT FROM OLD.amount
        OR NEW.paid_on_bill IS DISTINCT FROM OLD.paid_on_bill OR NEW.paper_bill_no IS DISTINCT FROM OLD.paper_bill_no THEN
        RAISE EXCEPTION 'sales_txn is insert-only – reverse the bill instead';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_sales_txn_guard BEFORE UPDATE OR DELETE ON sales_txn
    FOR EACH ROW EXECUTE FUNCTION sales_txn_guard();
CREATE TRIGGER tr_sales_txn_line_insert_only BEFORE UPDATE OR DELETE ON sales_txn_line
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();

-- Customer-damaged bottles (FR-37, BR-06) are recorded "At customer"; the record points to its bill (source SALES_TXN).
ALTER TABLE damage_record DROP CONSTRAINT ck_damage_record_location;
ALTER TABLE damage_record ADD CONSTRAINT ck_damage_record_location
    CHECK (location IS NULL OR location IN ('EMPTY_IN_STORE', 'FILLED_IN_STORE', 'AT_FACTORY', 'DURING_DELIVERY', 'AT_CUSTOMER'));
CREATE INDEX ix_damage_record_source ON damage_record (source_type, source_id);
