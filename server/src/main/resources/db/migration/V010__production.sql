-- M10 Production / Filling Factory (design 4.3 "Production", 5.1 factory dispatch / return effects)
-- One dispatch sends every bottle type to one factory (client feedback 08/10/2026); each bottle type is a batch that is
-- received back on its own (partial returns allowed). The charge per bottle is copied to the batch at dispatch (BR-11).
-- Numbers come from the sequences created in V001: FD-0001, FB-0001, FR-0001, FP-0001. All four tables are insert-only.

CREATE TABLE factory_dispatch (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_no   VARCHAR(20)  NOT NULL,
    factory_id    BIGINT       NOT NULL REFERENCES factory (id),
    dispatch_date DATE         NOT NULL,
    vehicle_no    VARCHAR(20),
    note          VARCHAR(200),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by    VARCHAR(50)  NOT NULL DEFAULT 'system',
    CONSTRAINT ux_factory_dispatch_no UNIQUE (dispatch_no)
);
CREATE INDEX ix_factory_dispatch_date ON factory_dispatch (dispatch_date);

CREATE TABLE factory_batch (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no          VARCHAR(20)   NOT NULL,
    dispatch_id       BIGINT        NOT NULL REFERENCES factory_dispatch (id),
    factory_id        BIGINT        NOT NULL REFERENCES factory (id),
    dispatch_date     DATE          NOT NULL,
    bottle_type_code  VARCHAR(10)   NOT NULL REFERENCES bottle_type (code),
    qty_sent          INTEGER       NOT NULL,
    charge_per_bottle NUMERIC(12,2) NOT NULL,
    vehicle_no        VARCHAR(20),
    note              VARCHAR(200),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by        VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_factory_batch_no UNIQUE (batch_no),
    CONSTRAINT ux_factory_batch_type UNIQUE (dispatch_id, bottle_type_code),
    CONSTRAINT ck_factory_batch_qty CHECK (qty_sent > 0),
    CONSTRAINT ck_factory_batch_charge CHECK (charge_per_bottle > 0)
);
CREATE INDEX ix_factory_batch_factory ON factory_batch (factory_id);

CREATE TABLE factory_return (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_no     VARCHAR(20)   NOT NULL,
    batch_id      BIGINT        NOT NULL REFERENCES factory_batch (id),
    return_date   DATE          NOT NULL,
    filled_qty    INTEGER       NOT NULL,
    rejected_qty  INTEGER       NOT NULL,
    reject_reason VARCHAR(200),
    cost          NUMERIC(14,2) NOT NULL,
    note          VARCHAR(200),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by    VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_factory_return_no UNIQUE (return_no),
    CONSTRAINT ck_factory_return_qty CHECK (filled_qty >= 0 AND rejected_qty >= 0 AND filled_qty + rejected_qty >= 1),
    CONSTRAINT ck_factory_return_reason CHECK (rejected_qty = 0 OR reject_reason IS NOT NULL),
    CONSTRAINT ck_factory_return_cost CHECK (cost >= 0)
);
CREATE INDEX ix_factory_return_batch ON factory_return (batch_id);
CREATE INDEX ix_factory_return_date ON factory_return (return_date);

-- Paid against a factory and month (period = 'YYYY-MM' of the returns' filling cost).
CREATE TABLE factory_payment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fp_no      VARCHAR(20)   NOT NULL,
    factory_id BIGINT        NOT NULL REFERENCES factory (id),
    period     VARCHAR(7)    NOT NULL,
    pay_date   DATE          NOT NULL,
    amount     NUMERIC(14,2) NOT NULL,
    method     VARCHAR(20)   NOT NULL,
    reference  VARCHAR(100),
    note       VARCHAR(200),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_factory_payment_no UNIQUE (fp_no),
    CONSTRAINT ck_factory_payment_period CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    CONSTRAINT ck_factory_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_factory_payment_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_factory_payment_ref CHECK (method = 'CASH' OR reference IS NOT NULL)
);
CREATE INDEX ix_factory_payment_factory ON factory_payment (factory_id, period);

CREATE TRIGGER tr_factory_dispatch_insert_only BEFORE UPDATE OR DELETE ON factory_dispatch
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_factory_batch_insert_only BEFORE UPDATE OR DELETE ON factory_batch
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_factory_return_insert_only BEFORE UPDATE OR DELETE ON factory_return
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_factory_payment_insert_only BEFORE UPDATE OR DELETE ON factory_payment
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
