-- M13 WhatsApp Business (design 4.3 whatsapp_message, 9.1, 9.2, FR-61)
-- Outbox: the business action (Left at door bill, monthly invoice, weekly reminder job) inserts a QUEUED row in its own
-- transaction; the sender job sends it through the Meta Cloud API (or the test sender when no real credentials are set),
-- so a Meta outage never blocks billing. Status updates come back through the webhook (SENT → DELIVERED → READ / FAILED).
-- The settings live in app_setting key 'whatsapp' (secrets AES-GCM encrypted, never returned).

CREATE TABLE whatsapp_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT        REFERENCES customer (id),
    type            VARCHAR(20)   NOT NULL,
    template        VARCHAR(60)   NOT NULL,
    to_number       VARCHAR(20)   NOT NULL,
    params          JSONB         NOT NULL DEFAULT '[]',
    status          VARCHAR(12)   NOT NULL,
    test_mode       BOOLEAN       NOT NULL DEFAULT FALSE,
    meta_message_id VARCHAR(100),
    error           VARCHAR(500),
    source_type     VARCHAR(20),
    source_id       BIGINT,
    attempts        INTEGER       NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    sent_at         TIMESTAMPTZ,
    status_at       TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by      VARCHAR(50)   NOT NULL DEFAULT 'system',
    updated_at      TIMESTAMPTZ,
    updated_by      VARCHAR(50),
    version         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_whatsapp_type CHECK (type IN ('LEFT_AT_DOOR', 'PAYMENT_REMINDER', 'MONTHLY_INVOICE', 'TEST')),
    CONSTRAINT ck_whatsapp_status CHECK (status IN ('QUEUED', 'SENT', 'DELIVERED', 'READ', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_whatsapp_params CHECK (jsonb_typeof(params) = 'array'),
    CONSTRAINT ck_whatsapp_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_whatsapp_customer CHECK (type = 'TEST' OR customer_id IS NOT NULL)
);
CREATE INDEX ix_whatsapp_message_status ON whatsapp_message (status, next_attempt_at);
CREATE INDEX ix_whatsapp_message_customer ON whatsapp_message (customer_id, type, created_at);
CREATE INDEX ix_whatsapp_message_created ON whatsapp_message (created_at);
CREATE UNIQUE INDEX ux_whatsapp_meta_id ON whatsapp_message (meta_message_id) WHERE meta_message_id IS NOT NULL;

