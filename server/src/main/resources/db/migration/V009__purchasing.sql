-- M09 Purchasing (design 4.3 "Purchasing", 5.1 goods receipt effects)
-- Quotation requests to suppliers, their quotations (compared side by side, one chosen by the owner), purchase orders
-- made only from the chosen quotation, goods received against a sent PO, supplier payments.
-- Numbers come from the sequences created in V001: QR-2026-001 (yearly), SQ-0001, PO-2026-0001 (yearly), GRN-0001, SP-0001.

-- ---------------------------------------------------------------- quotation requests (FR-15)
CREATE TABLE quotation_request (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_no        VARCHAR(20)  NOT NULL,
    request_date DATE         NOT NULL,
    required_by  DATE,
    note         VARCHAR(300),
    status       VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by   VARCHAR(50)  NOT NULL DEFAULT 'system',
    updated_at   TIMESTAMPTZ,
    updated_by   VARCHAR(50),
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ux_quotation_request_no UNIQUE (qr_no),
    CONSTRAINT ck_quotation_request_status CHECK (status IN ('OPEN', 'QUOTES_RECEIVED', 'SELECTED', 'CLOSED'))
);
CREATE INDEX ix_quotation_request_date ON quotation_request (request_date);

-- Items asked for: empty bottles (bottle type code) or products (product code).
CREATE TABLE qr_item (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_id     BIGINT      NOT NULL REFERENCES quotation_request (id) ON DELETE CASCADE,
    line_no   INTEGER     NOT NULL,
    item_type VARCHAR(10) NOT NULL,
    item_code VARCHAR(10) NOT NULL,
    qty       INTEGER     NOT NULL,
    CONSTRAINT ck_qr_item_type CHECK (item_type IN ('BOTTLE', 'PRODUCT')),
    CONSTRAINT ck_qr_item_qty CHECK (qty > 0),
    CONSTRAINT ux_qr_item UNIQUE (qr_id, item_code)
);

-- Suppliers asked to quote.
CREATE TABLE qr_supplier (
    qr_id       BIGINT NOT NULL REFERENCES quotation_request (id) ON DELETE CASCADE,
    supplier_id BIGINT NOT NULL REFERENCES supplier (id),
    PRIMARY KEY (qr_id, supplier_id)
);

-- ---------------------------------------------------------------- supplier quotations (FR-16, FR-17)
CREATE TABLE quotation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_no         VARCHAR(20)  NOT NULL,
    qr_id            BIGINT       NOT NULL REFERENCES quotation_request (id),
    supplier_id      BIGINT       NOT NULL REFERENCES supplier (id),
    supplier_ref     VARCHAR(50),
    quote_date       DATE         NOT NULL,
    valid_until      DATE         NOT NULL,
    delivery_days    INTEGER      NOT NULL,
    notes            VARCHAR(300),
    attachment_path  VARCHAR(200),
    attachment_name  VARCHAR(120),
    selected         BOOLEAN      NOT NULL DEFAULT FALSE,
    selection_reason VARCHAR(300),
    selected_by      VARCHAR(50),
    selected_on      DATE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       VARCHAR(50)  NOT NULL DEFAULT 'system',
    updated_at       TIMESTAMPTZ,
    updated_by       VARCHAR(50),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ux_quotation_no UNIQUE (quote_no),
    CONSTRAINT ux_quotation_supplier UNIQUE (qr_id, supplier_id),
    CONSTRAINT ck_quotation_valid CHECK (valid_until >= quote_date),
    CONSTRAINT ck_quotation_days CHECK (delivery_days >= 0),
    CONSTRAINT ck_quotation_selected CHECK (NOT selected OR selection_reason IS NOT NULL)
);
-- The owner chooses at most one quotation per request.
CREATE UNIQUE INDEX ux_quotation_chosen ON quotation (qr_id) WHERE selected;

-- Unit price per requested item; null = not quoted.
CREATE TABLE quotation_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT        NOT NULL REFERENCES quotation (id) ON DELETE CASCADE,
    item_code    VARCHAR(10)   NOT NULL,
    unit_price   NUMERIC(12,2),
    CONSTRAINT ck_quotation_line_price CHECK (unit_price IS NULL OR unit_price > 0),
    CONSTRAINT ux_quotation_line UNIQUE (quotation_id, item_code)
);

-- ---------------------------------------------------------------- purchase orders (FR-18, FR-19, BR-10)
CREATE TABLE purchase_order (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_no         VARCHAR(20)  NOT NULL,
    qr_id         BIGINT       NOT NULL REFERENCES quotation_request (id),
    quotation_id  BIGINT       NOT NULL REFERENCES quotation (id),
    supplier_id   BIGINT       NOT NULL REFERENCES supplier (id),
    po_date       DATE         NOT NULL,
    expected_date DATE         NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    notes         VARCHAR(300),
    approved_by   VARCHAR(50),
    approved_on   DATE,
    sent_on       DATE,
    cancel_reason VARCHAR(300),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by    VARCHAR(50)  NOT NULL DEFAULT 'system',
    updated_at    TIMESTAMPTZ,
    updated_by    VARCHAR(50),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ux_purchase_order_no UNIQUE (po_no),
    CONSTRAINT ck_purchase_order_status CHECK (status IN ('DRAFT', 'APPROVED', 'SENT', 'PARTLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    CONSTRAINT ck_purchase_order_cancel CHECK (status <> 'CANCELLED' OR cancel_reason IS NOT NULL)
);
-- One active (not cancelled) PO per quotation.
CREATE UNIQUE INDEX ux_purchase_order_active ON purchase_order (quotation_id) WHERE status <> 'CANCELLED';
CREATE INDEX ix_purchase_order_supplier ON purchase_order (supplier_id);
CREATE INDEX ix_purchase_order_status ON purchase_order (status);

CREATE TABLE po_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id        BIGINT        NOT NULL REFERENCES purchase_order (id) ON DELETE CASCADE,
    line_no      INTEGER       NOT NULL,
    item_type    VARCHAR(10)   NOT NULL,
    item_code    VARCHAR(10)   NOT NULL,
    qty          INTEGER       NOT NULL,
    unit_price   NUMERIC(12,2) NOT NULL,
    received_qty INTEGER       NOT NULL DEFAULT 0,
    damaged_qty  INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT ck_po_line_type CHECK (item_type IN ('BOTTLE', 'PRODUCT')),
    CONSTRAINT ck_po_line_qty CHECK (qty > 0),
    CONSTRAINT ck_po_line_price CHECK (unit_price > 0),
    CONSTRAINT ck_po_line_received CHECK (received_qty BETWEEN 0 AND qty),
    CONSTRAINT ck_po_line_damaged CHECK (damaged_qty BETWEEN 0 AND received_qty),
    CONSTRAINT ux_po_line UNIQUE (po_id, item_code)
);

-- Every status change (insert-only).
CREATE TABLE po_status_history (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id    BIGINT       NOT NULL REFERENCES purchase_order (id) ON DELETE CASCADE,
    status   VARCHAR(20)  NOT NULL,
    ts       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    username VARCHAR(50)  NOT NULL,
    note     VARCHAR(300)
);
CREATE INDEX ix_po_status_history_po ON po_status_history (po_id, id);

-- ---------------------------------------------------------------- goods receipts (FR-20, BR-10) – insert-only
CREATE TABLE goods_receipt (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grn_no        VARCHAR(20)   NOT NULL,
    po_id         BIGINT        NOT NULL REFERENCES purchase_order (id),
    supplier_id   BIGINT        NOT NULL REFERENCES supplier (id),
    received_date DATE          NOT NULL,
    delivery_note VARCHAR(50),
    note          VARCHAR(300),
    value         NUMERIC(14,2) NOT NULL,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by    VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_goods_receipt_no UNIQUE (grn_no),
    CONSTRAINT ck_goods_receipt_value CHECK (value >= 0)
);
CREATE INDEX ix_goods_receipt_supplier ON goods_receipt (supplier_id, received_date);
CREATE INDEX ix_goods_receipt_po ON goods_receipt (po_id);

-- Good = received − damaged goes into stock and is paid for; damaged is neither.
CREATE TABLE grn_line (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grn_id     BIGINT        NOT NULL REFERENCES goods_receipt (id),
    po_line_id BIGINT        NOT NULL REFERENCES po_line (id),
    item_type  VARCHAR(10)   NOT NULL,
    item_code  VARCHAR(10)   NOT NULL,
    received   INTEGER       NOT NULL,
    damaged    INTEGER       NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    CONSTRAINT ck_grn_line_received CHECK (received > 0),
    CONSTRAINT ck_grn_line_damaged CHECK (damaged BETWEEN 0 AND received)
);
CREATE INDEX ix_grn_line_grn ON grn_line (grn_id);

-- ---------------------------------------------------------------- supplier payments (FR-21) – insert-only
CREATE TABLE supplier_payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sp_no       VARCHAR(20)   NOT NULL,
    supplier_id BIGINT        NOT NULL REFERENCES supplier (id),
    po_id       BIGINT        REFERENCES purchase_order (id),
    pay_date    DATE          NOT NULL,
    amount      NUMERIC(14,2) NOT NULL,
    method      VARCHAR(20)   NOT NULL,
    reference   VARCHAR(100),
    note        VARCHAR(300),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by  VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_supplier_payment_no UNIQUE (sp_no),
    CONSTRAINT ck_supplier_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_supplier_payment_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_supplier_payment_ref CHECK (method = 'CASH' OR reference IS NOT NULL)
);
CREATE INDEX ix_supplier_payment_supplier ON supplier_payment (supplier_id, pay_date);

CREATE TRIGGER tr_po_status_history_insert_only BEFORE UPDATE OR DELETE ON po_status_history
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_goods_receipt_insert_only BEFORE UPDATE OR DELETE ON goods_receipt
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_grn_line_insert_only BEFORE UPDATE OR DELETE ON grn_line
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_supplier_payment_insert_only BEFORE UPDATE OR DELETE ON supplier_payment
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
