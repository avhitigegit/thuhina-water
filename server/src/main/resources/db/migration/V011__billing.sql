-- M11 Billing & payments (design 4.3 "Billing", 5.6)
-- Customer payments lower the account balance (customer_account) in the same transaction; monthly invoices list the bills
-- of a Monthly bill customer's month. Numbers come from the sequences created in V001: RC-00001 (never resets) and
-- INV-YYMM-0001 (monthly, by the invoice period). All three tables are insert-only.

CREATE TABLE monthly_invoice (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no      VARCHAR(20)   NOT NULL,
    customer_id     BIGINT        NOT NULL REFERENCES customer (id),
    period          VARCHAR(7)    NOT NULL,
    period_from     DATE          NOT NULL,
    period_to       DATE          NOT NULL,
    invoice_date    DATE          NOT NULL,
    due_date        DATE          NOT NULL,
    opening_balance NUMERIC(14,2) NOT NULL,
    charges         NUMERIC(14,2) NOT NULL,
    paid_on_bills   NUMERIC(14,2) NOT NULL,
    payments        NUMERIC(14,2) NOT NULL,
    amount          NUMERIC(14,2) NOT NULL,
    total_due       NUMERIC(14,2) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by      VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_monthly_invoice_no UNIQUE (invoice_no),
    CONSTRAINT ux_monthly_invoice_period UNIQUE (customer_id, period),
    CONSTRAINT ck_monthly_invoice_period CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    CONSTRAINT ck_monthly_invoice_dates CHECK (period_to >= period_from AND due_date >= invoice_date),
    CONSTRAINT ck_monthly_invoice_amount CHECK (amount = charges - paid_on_bills),
    CONSTRAINT ck_monthly_invoice_total CHECK (total_due = opening_balance + amount - payments)
);
CREATE INDEX ix_monthly_invoice_period ON monthly_invoice (period);

-- The bills listed on an invoice.
CREATE TABLE invoice_txn (
    invoice_id BIGINT NOT NULL REFERENCES monthly_invoice (id),
    txn_id     BIGINT NOT NULL REFERENCES sales_txn (id),
    PRIMARY KEY (invoice_id, txn_id)
);
CREATE INDEX ix_invoice_txn_txn ON invoice_txn (txn_id);

CREATE TABLE customer_payment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no     VARCHAR(20)   NOT NULL,
    customer_id    BIGINT        NOT NULL REFERENCES customer (id),
    pay_date       DATE          NOT NULL,
    amount         NUMERIC(14,2) NOT NULL,
    method         VARCHAR(20)   NOT NULL,
    reference      VARCHAR(100),
    bank           VARCHAR(100),
    cheque_date    DATE,
    invoice_id     BIGINT        REFERENCES monthly_invoice (id),
    note           VARCHAR(200),
    balance_before NUMERIC(14,2) NOT NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by     VARCHAR(50)   NOT NULL DEFAULT 'system',
    CONSTRAINT ux_customer_payment_no UNIQUE (receipt_no),
    CONSTRAINT ck_customer_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_customer_payment_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_customer_payment_ref CHECK (method = 'CASH' OR reference IS NOT NULL),
    CONSTRAINT ck_customer_payment_cheque CHECK (method = 'CHEQUE' OR (bank IS NULL AND cheque_date IS NULL))
);
CREATE INDEX ix_customer_payment_customer ON customer_payment (customer_id, pay_date);
CREATE INDEX ix_customer_payment_date ON customer_payment (pay_date);
CREATE INDEX ix_customer_payment_invoice ON customer_payment (invoice_id) WHERE invoice_id IS NOT NULL;

-- Money paid on bills, for the "Recent payments and cash collected" list.
CREATE INDEX ix_sales_txn_paid ON sales_txn (txn_date) WHERE paid_on_bill > 0;

CREATE TRIGGER tr_monthly_invoice_insert_only BEFORE UPDATE OR DELETE ON monthly_invoice
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_invoice_txn_insert_only BEFORE UPDATE OR DELETE ON invoice_txn
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
CREATE TRIGGER tr_customer_payment_insert_only BEFORE UPDATE OR DELETE ON customer_payment
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
