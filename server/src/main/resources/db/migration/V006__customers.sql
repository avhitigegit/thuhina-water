-- M05 Customers (design 4.3 "Customers", 5.4, 5.5, 5.6)
-- Customers with delivery and payment details, usual quantities, bottle balances (changed only by the Ledger Engine),
-- the account balance, and agreed water prices. Codes come from the CUSTOMER (C0001) and CUSTOMER_PRICE (CP0001)
-- sequences created in V001.

CREATE TABLE customer (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(10)   NOT NULL,
    name               VARCHAR(120)  NOT NULL,
    address            VARCHAR(250)  NOT NULL,
    area_id            BIGINT        NOT NULL REFERENCES area (id),
    phone              VARCHAR(20)   NOT NULL,
    customer_type_id   BIGINT        NOT NULL REFERENCES customer_type (id),
    delivery_day       SMALLINT      NOT NULL,
    cycle_weeks        SMALLINT      NOT NULL,
    next_delivery_date DATE          NOT NULL,
    pay_type           VARCHAR(15)   NOT NULL,
    credit_limit       NUMERIC(12,2) NOT NULL DEFAULT 0,
    terms_days         INTEGER       NOT NULL DEFAULT 0,
    registered_on      DATE          NOT NULL,
    status             VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE',
    status_date        DATE,
    status_reason      VARCHAR(250),
    notes              VARCHAR(500),
    whatsapp_opt_in    BOOLEAN       NOT NULL DEFAULT FALSE,
    whatsapp_number    VARCHAR(20),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by         VARCHAR(50)   NOT NULL DEFAULT 'system',
    updated_at         TIMESTAMPTZ,
    updated_by         VARCHAR(50),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ux_customer_code UNIQUE (code),
    CONSTRAINT ck_customer_day CHECK (delivery_day BETWEEN 1 AND 7),
    CONSTRAINT ck_customer_cycle CHECK (cycle_weeks BETWEEN 1 AND 4),
    CONSTRAINT ck_customer_pay_type CHECK (pay_type IN ('CASH', 'CREDIT', 'MONTHLY_BILL')),
    CONSTRAINT ck_customer_credit CHECK (
        (pay_type = 'CASH' AND credit_limit = 0 AND terms_days = 0)
        OR (pay_type <> 'CASH' AND credit_limit > 0 AND terms_days IN (7, 14, 30, 45, 60))),
    CONSTRAINT ck_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_customer_name ON customer (lower(name));
CREATE INDEX ix_customer_phone ON customer (phone);
CREATE INDEX ix_customer_area_day_status ON customer (area_id, delivery_day, status);
CREATE INDEX ix_customer_next_delivery ON customer (next_delivery_date);

CREATE TABLE customer_usual_qty (
    customer_id      BIGINT      NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    bottle_type_code VARCHAR(10) NOT NULL REFERENCES bottle_type (code),
    qty              INTEGER     NOT NULL,
    PRIMARY KEY (customer_id, bottle_type_code),
    CONSTRAINT ck_customer_usual_qty CHECK (qty >= 0)
);

-- Bottles with the customer, empties still to collect, bottles owed – only the Ledger Engine changes them.
CREATE TABLE customer_bottle_balance (
    customer_id      BIGINT      NOT NULL REFERENCES customer (id),
    bottle_type_code VARCHAR(10) NOT NULL REFERENCES bottle_type (code),
    held             INTEGER     NOT NULL DEFAULT 0,
    to_collect       INTEGER     NOT NULL DEFAULT 0,
    owed             INTEGER     NOT NULL DEFAULT 0,
    PRIMARY KEY (customer_id, bottle_type_code),
    CONSTRAINT ck_cbb_held CHECK (held >= 0),
    CONSTRAINT ck_cbb_to_collect CHECK (to_collect >= 0),
    CONSTRAINT ck_cbb_owed CHECK (owed >= 0)
);

-- Account balance (positive = the customer owes), kept in the same transaction as every charge and payment (M06, M11).
CREATE TABLE customer_account (
    customer_id BIGINT        PRIMARY KEY REFERENCES customer (id),
    balance     NUMERIC(12,2) NOT NULL DEFAULT 0
);

-- A new bottle type also gets balance rows for every customer (the stock rows come from V005).
CREATE OR REPLACE FUNCTION bottle_type_stock_rows() RETURNS trigger AS $$
BEGIN
    INSERT INTO stock_balance (bottle_type_code, bucket)
    SELECT NEW.code, k.bucket
    FROM (VALUES ('EMPTY'), ('FACTORY'), ('FILLED'), ('CUSTOMERS'), ('WRITTEN_OFF')) AS k (bucket)
    ON CONFLICT DO NOTHING;
    INSERT INTO customer_bottle_balance (customer_id, bottle_type_code)
    SELECT c.id, NEW.code FROM customer c
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------- agreed water prices (FR-05, BR-08)
-- At most one non-cancelled row covers any date for a customer + bottle type (kept by the service: a new row closes the
-- previous one the day before and cancels later ones). Bills store their own price, so old bills never change.
CREATE TABLE customer_price (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cp_no                 VARCHAR(10)   NOT NULL,
    customer_id           BIGINT        NOT NULL REFERENCES customer (id),
    bottle_type_code      VARCHAR(10)   NOT NULL REFERENCES bottle_type (code),
    price                 NUMERIC(12,2) NOT NULL,
    standard_at_set       NUMERIC(12,2),
    valid_from            DATE          NOT NULL,
    valid_until           DATE,
    reason                VARCHAR(250)  NOT NULL,
    customer_quotation_id BIGINT,
    cancelled             BOOLEAN       NOT NULL DEFAULT FALSE,
    cancel_reason         VARCHAR(250),
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by            VARCHAR(50)   NOT NULL DEFAULT 'system',
    updated_at            TIMESTAMPTZ,
    updated_by            VARCHAR(50),
    version               BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ux_customer_price_no UNIQUE (cp_no),
    CONSTRAINT ck_customer_price CHECK (price > 0),
    CONSTRAINT ck_customer_price_dates CHECK (valid_until IS NULL OR valid_until >= valid_from)
);
CREATE INDEX ix_customer_price_lookup ON customer_price (customer_id, bottle_type_code, valid_from);
