CREATE TABLE factory_payment_bill (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT        NOT NULL REFERENCES factory_payment (id),
    return_id  BIGINT        NOT NULL REFERENCES factory_return (id),
    amount     NUMERIC(14,2) NOT NULL,
    CONSTRAINT ux_factory_payment_bill UNIQUE (payment_id, return_id),
    CONSTRAINT ck_factory_payment_bill_amount CHECK (amount > 0)
);
CREATE INDEX ix_factory_payment_bill_return ON factory_payment_bill (return_id);

CREATE TRIGGER tr_factory_payment_bill_insert_only BEFORE UPDATE OR DELETE ON factory_payment_bill
    FOR EACH ROW EXECUTE FUNCTION ledger_insert_only();
