-- Client 21/11/2026:
-- 1. Payment types for money in and money out: Cash, Card, Online transfer, Cheque, Bill to Bill.
--    BANK_TRANSFER keeps its stored name (now shown as "Online transfer"); CARD and BILL_TO_BILL are new.
--    A card slip number is optional; online transfer, cheque and Bill to Bill need their reference (Bill to Bill = the
--    number of the earlier bill it pays).
-- 2. Factory payments are Bill to Bill: each payment pays the filling bills the user ticks (a bill = one factory return,
--    FR-0001, with its filling cost). factory_payment_bill holds how much of the payment went on each bill.
--    Payments made before this keep clearing the oldest bills first.

